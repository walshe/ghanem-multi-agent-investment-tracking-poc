-- Checkouts. Money is integer minor units plus an ISO 4217 currency code.
-- "version" is the optimistic locking column: every update is
--   UPDATE ... SET version = version + 1 WHERE id = ? AND version = ?
-- so two writers working from the same snapshot can't both succeed.
CREATE TABLE checkout (
    id               UUID                     NOT NULL,
    status           VARCHAR(20)              NOT NULL,
    amount_minor     BIGINT                   NOT NULL,
    currency         CHAR(3)                  NOT NULL,
    payment_id       VARCHAR(255),
    refund_requested BOOLEAN                  DEFAULT FALSE NOT NULL,
    -- The provider answered our cancel with 409 (or we couldn't reach it), so the payment
    -- may still complete. The scheduled job keeps checking it until it is final.
    cancel_refused   BOOLEAN                  DEFAULT FALSE NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_checkout PRIMARY KEY (id),
    CONSTRAINT ck_checkout_status CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'FAILED', 'EXPIRED')),
    CONSTRAINT ck_checkout_amount CHECK (amount_minor >= 100)
);

-- Every payment event that passed the signature check, plus events from reconciliation.
-- event_id is the idempotency key: inserting the same event twice fails on uk_payment_event_event_id.
-- checkout_id is the raw value from the callback and deliberately has no foreign key,
-- so a callback for an unknown checkout can still be recorded (as FLAGGED).
CREATE TABLE payment_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    event_id     VARCHAR(255)             NOT NULL,
    checkout_id  VARCHAR(255)             NOT NULL,
    payment_id   VARCHAR(255),
    status       VARCHAR(20)              NOT NULL,
    amount_minor BIGINT                   NOT NULL,
    currency     VARCHAR(3)               NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE,
    outcome      VARCHAR(20)              NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_payment_event PRIMARY KEY (id),
    CONSTRAINT uk_payment_event_event_id UNIQUE (event_id),
    CONSTRAINT ck_payment_event_status CHECK (status IN ('PROCESSING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_payment_event_outcome CHECK (outcome IN ('APPLIED', 'IGNORED_STALE', 'FLAGGED'))
);

CREATE INDEX ix_payment_event_checkout_id ON payment_event (checkout_id);
CREATE INDEX ix_checkout_status ON checkout (status);
